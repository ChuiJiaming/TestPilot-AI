"""Generate an operationId-level inventory of candidate versus registered API routes."""

import argparse
from pathlib import Path

import yaml

from apps.api.app.main import create_app


ROOT = Path(__file__).resolve().parents[3]
METHODS = {"get", "post", "put", "patch", "delete", "options", "head"}


def operations(document):
    rows = []
    for path, path_item in document.get("paths", {}).items():
        for method, operation in path_item.items():
            if method.lower() not in METHODS or not isinstance(operation, dict):
                continue
            rows.append({
                "method": method.upper(),
                "path": path,
                "operation_id": operation.get("operationId", ""),
                "tags": operation.get("tags", []),
            })
    return rows


def build_report() -> str:
    contract = yaml.safe_load((ROOT / "api" / "openapi.yaml").read_text(encoding="utf-8"))
    baseline = set((ROOT / "contracts" / "openapi_v10_3_original_operation_ids.txt")
                   .read_text(encoding="utf-8").splitlines())
    candidate_rows = operations(contract)
    runtime_rows = operations(create_app().openapi())
    runtime_ids = {row["operation_id"] for row in runtime_rows}
    tests = list((ROOT / "tests").glob("test_*.py"))

    baseline_runtime = len(baseline & runtime_ids)
    additive_runtime = len((set(row["operation_id"] for row in candidate_rows) - baseline) & runtime_ids)
    lines = [
        "# Candidate API Runtime Coverage",
        "",
        "> Generated by `python -m apps.api.scripts.report_runtime_api_coverage`.",
        "> Route registration is not proof of DTO, authorization, persistence, or HTTP contract conformance.",
        "> Test source references are discovery hints, not test coverage claims.",
        "",
        f"- Baseline operations: **{len(baseline)}**",
        f"- Candidate operations: **{len(candidate_rows)}** (baseline plus {len(candidate_rows) - len(baseline)} additive operations)",
        f"- Baseline operations with a runtime route registered: **{baseline_runtime}/{len(baseline)}**",
        f"- Baseline operations without a runtime route: **{len(baseline) - baseline_runtime}**",
        f"- Additive operations with a runtime route registered: **{additive_runtime}/{len(candidate_rows) - len(baseline)}**",
        "",
        "Data entities, frontend entry points, and acceptance-test groups remain mapped at module level in [the traceability matrix](traceability-matrix.md). This report does not invent one-to-one field mappings where V10.3 does not define them.",
        "",
        "| Baseline | Method | Path | operationId | OpenAPI tag | Runtime route | Test source references |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in sorted(candidate_rows, key=lambda item: (item["operation_id"], item["method"], item["path"])):
        operation_id = row["operation_id"]
        references = [test_file.name for test_file in tests
                      if operation_id and operation_id in test_file.read_text(encoding="utf-8")]
        lines.append("| {baseline} | {method} | `{path}` | `{operation_id}` | {tag} | {runtime} | {references} |".format(
            baseline="Yes" if operation_id in baseline else "Additive",
            method=row["method"],
            path=row["path"],
            operation_id=operation_id,
            tag=", ".join(row["tags"]) or "(untagged)",
            runtime="Registered" if operation_id in runtime_ids else "Missing",
            references=", ".join(references) if references else "—",
        ))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "api-runtime-coverage.md")
    args = parser.parse_args()
    report = build_report()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"Wrote {args.output.relative_to(ROOT)}")
    print(" ".join(line for line in report.splitlines() if line.startswith("- ")))


if __name__ == "__main__":
    main()
